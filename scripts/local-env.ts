/**
 * Writes .env.local for the local Supabase stack (CRU-34), so the app runs
 * against `bun run db:start` instead of a hosted project. Run it after
 * db:start: `bun run db:env`.
 *
 * Bun loads .env.local ahead of .env, so if you also keep hosted values in
 * .env, these win while the file exists. Delete .env.local to switch back.
 *
 * Everything written here is local-only: the CLI's standard demo keys and
 * freshly generated secrets. Nothing is read from or sent to a hosted project.
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const CLI = "supabase@2.120.0";
const FILE = ".env.local";

const proc = Bun.spawnSync(["bunx", CLI, "status", "-o", "env"], { stderr: "pipe" });
if (proc.exitCode !== 0) {
  console.error("The local Supabase stack isn't running. Start it with `bun run db:start`.");
  process.exit(1);
}
const status = Object.fromEntries(
  proc.stdout
    .toString()
    .split("\n")
    .map((line) => line.match(/^([A-Z_]+)="?(.*?)"?$/))
    .filter((m): m is RegExpMatchArray => m !== null)
    .map((m) => [m[1], m[2]]),
);
for (const key of ["API_URL", "ANON_KEY", "SERVICE_ROLE_KEY"]) {
  if (!status[key]) {
    console.error(
      `\`supabase status\` didn't report ${key}. Is the full stack running (db:start, not db start)?`,
    );
    process.exit(1);
  }
}

// Keep secrets stable across re-runs so a running dev server isn't surprised.
const previous = existsSync(FILE) ? readFileSync(FILE, "utf8") : "";
const keep = (name: string) => previous.match(new RegExp(`^${name}="([0-9a-f]{64})"$`, "m"))?.[1];
const hex = () => randomBytes(32).toString("hex");

const values: Record<string, string> = {
  SUPABASE_URL: status["API_URL"]!,
  VITE_SUPABASE_URL: status["API_URL"]!,
  SUPABASE_PUBLISHABLE_KEY: status["ANON_KEY"]!,
  VITE_SUPABASE_PUBLISHABLE_KEY: status["ANON_KEY"]!,
  // No SUPABASE_PROJECT_ID: Bun loads this file for every `bun run` script,
  // and the Supabase CLI would read it as a project override, so db:reset and
  // friends would look for the wrong local stack.
  SUPABASE_SERVICE_ROLE_KEY: status["SERVICE_ROLE_KEY"]!,
  ICS_URL_ENCRYPTION_KEY: keep("ICS_URL_ENCRYPTION_KEY") ?? hex(),
  CRON_SECRET: keep("CRON_SECRET") ?? hex(),
};

writeFileSync(
  FILE,
  [
    "# Generated by `bun run db:env` for the LOCAL Supabase stack. Safe to delete.",
    "# Local demo keys and random secrets only; never use these anywhere else.",
    ...Object.entries(values).map(([k, v]) => `${k}="${v}"`),
    "",
  ].join("\n"),
);
console.log(`Wrote ${FILE} for ${values["SUPABASE_URL"]}. Start the app with \`bun run dev\`.`);
